"""Generate a shareable Markdown report for a dataset (``elake report``).

One command aggregating everything embodied-lake knows about a dataset:
identity (inspect), structural QC, content scores, lineage/catalog entry, and
snapshot pin. Designed to be pasted into PRs, dataset cards, and onboarding
docs — the same artifacts used to validate the converters against official
conversions.
"""

from __future__ import annotations

from pathlib import Path

from ..inspect import inspect
from .scoring import score_dataset
from .structural import qc_dataset


def render_report(dataset: str | Path, out: str | Path | None = None) -> Path:
    root = Path(dataset)
    card = inspect(str(root))
    qc = qc_dataset(root)
    scored = score_dataset(root)

    lines: list[str] = []
    a = lines.append
    a(f"# Dataset report — `{root.name}`")
    a("")
    a(f"- **format**: {card.codebase_version} · **robot**: {card.robot_type} · "
      f"**fps**: {card.fps}")
    a(f"- **episodes**: {card.total_episodes} · **frames**: {card.total_frames} · "
      f"**tasks**: {card.total_tasks}")
    a(f"- **splits**: `{card.splits}`")
    a(f"- **features** ({len(card.features)}): " + ", ".join(
        f"`{name}`" for name in list(card.features)[:10])
        + (" …" if len(card.features) > 10 else ""))
    a("")
    a("## Structural QC")
    a("")
    verdict = "PASS ✅" if qc.ok else "FAIL ❌"
    a(f"**{verdict}** — {len(qc.issues)} issue(s)")
    for i in qc.issues[:10]:
        a(f"- `{i.severity}` {i.message}")
    a("")
    a("## Content scores")
    a("")
    if scored.episodes:
        mean = scored.mean_score
        flagged = [s for s in scored.episodes if s.findings]
        a(f"**mean {mean:.1f}/100** over {len(scored.episodes)} episodes · "
          f"{len(flagged)} episode(s) with findings")
        a("")
        a("| episode | score | findings |")
        a("|---|---|---|")
        for s in scored.episodes:
            findings = "<br>".join(f"{f.check}: {f.detail}" for f in s.findings) or "—"
            a(f"| {s.episode_index} | {s.score:.0f} | {findings} |")
        if len(scored.episodes) > 30:
            a("")
            a(f"(showing all {len(scored.episodes)}; truncated tables live in the CLI output)")
    else:
        a("_no scored features (dataset may be video-only or unreadable)_")
    a("")
    a("## Provenance")
    a("")
    a(f"- report generated by `elake report` (embodied-lake) · "
      f"path: `{root}`")
    a("")

    text = "\n".join(lines)
    out_path = Path(out) if out else root.parent / f"{root.name}.report.md"
    out_path.write_text(text, encoding="utf-8")
    return out_path
